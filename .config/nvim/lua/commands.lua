local cmd = vim.api.nvim_create_user_command
local function install_parsers()
  return require("nvim-treesitter").install(require("languages").parsers)
end
cmd("TSInstallAll", install_parsers, { desc = "Install configured language parsers" })
cmd("MasonInstallAll", function()
  vim.cmd("MasonInstall " .. table.concat(require("languages").mason_packages, " "))
end, { desc = "Install declared language servers and formatters" })
cmd("ToolsInstall", function()
  vim.cmd("MasonInstallAll")
  install_parsers()
end, { desc = "Install all essential language tools and parsers" })
cmd("ToolsEnable", function()
  require("plugins.configs.lspconfig").enable()
end, { desc = "Enable newly installed language servers" })
cmd("ToolsStatus", function()
  local lsp = require("plugins.configs.lspconfig")
  print("Available LSPs: " .. table.concat(lsp.enabled, ", "))
  print("Unavailable LSPs: " .. vim.inspect(lsp.unavailable))
  print("Managed tools: " .. table.concat(require("mason-registry").get_installed_package_names(), ", "))
end, { desc = "Show available language services and managed tools" })
